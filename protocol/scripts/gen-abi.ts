/** Copies ABIs and bytecode from the Foundry build into src/shared/artifacts.ts. Run after `forge build`. */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const out = join(here, "../../contracts/out");
const pick = (file: string, name: string) => {
  const j = JSON.parse(readFileSync(join(out, file, `${name}.json`), "utf8"));
  return { abi: j.abi, bytecode: j.bytecode.object as string, deployed: j.deployedBytecode.object as string };
};
const probeJobs = pick("ProbeJobs.sol", "ProbeJobs");
const mockUsd = pick("MockUSD.sol", "MockUSD");
const src =
  `// Generated by scripts/gen-abi.ts from contracts/out. Do not edit by hand.\n` +
  `export const probeJobsAbi = ${JSON.stringify(probeJobs.abi, null, 2)} as const;\n\n` +
  `export const probeJobsBytecode = "${probeJobs.bytecode}" as const;\n\n` +
  `export const probeJobsDeployedBytecode = "${probeJobs.deployed}" as const;\n\n` +
  `export const mockUsdAbi = ${JSON.stringify(mockUsd.abi, null, 2)} as const;\n\n` +
  `export const mockUsdBytecode = "${mockUsd.bytecode}" as const;\n`;
writeFileSync(join(here, "../src/shared/artifacts.ts"), src);
console.log("wrote src/shared/artifacts.ts");
